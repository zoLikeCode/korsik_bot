def localized(text):
    return {"text_ty": text, "text_vy": text}


def option(value, label, **extra):
    return {"value": value, "label": localized(label), **extra}


def question(
    key, prompt, typ="SINGLE_CHOICE", options=None, comment=None, binding=None
):
    q = {
        "question_key": key,
        "type": typ,
        "prompt": localized(prompt),
        "required": True,
        "source_requiredness": "REQUIRED",
        "allow_decline": True,
    }
    if options:
        q["options"] = [
            option(v, t, **x) if len(o) > 2 else option(v, t)
            for o in options
            for v, t, *extra in [o]
            for x in [extra[0] if extra else {}]
        ]
    if typ == "NUMERIC":
        q.update(minimum=1, maximum=10)
    if typ == "TEXT":
        q["max_text_length"] = 6000
    if typ == "PHOTO":
        q["attachment_purpose"] = "EMPLOYEE_PHOTO"
    if typ == "MULTI_CHOICE":
        q.update(min_selected=1, max_selected=len(options))
    if comment:
        q["comment_when"] = {
            "kind": "ANSWER",
            "question_key": key,
            "operator": comment[0],
            "value": comment[1],
        }
        q["comment_prompt"] = localized(
            "Расскажите подробнее, пожалуйста. Можно отказаться от комментария."
        )
    if binding:
        q["answer_binding"] = binding
    return q


def survey_def(key, questions):
    for a, b in zip(questions, questions[1:]):
        a["next_question_key"] = b["question_key"]
    return {
        "survey_key": key,
        "start_question_key": questions[0]["question_key"],
        "questions": questions,
        "expiry_days": 7,
        "reminders": {
            "anchor": "FIRST_QUESTION_ACCEPTED",
            "offset_local_days": [1, 2],
            "suppress_in_human_mode": True,
        },
        "thank_you": localized("Спасибо за обратную связь! Ответы сохранены. 💙"),
    }


